"""Composite primary keys that mix a generated field with a supplied one.

The shape a partitioned table forces: its key has to include the partition
column, and that column is an ordinary one nobody can generate on the
model's behalf -- while a surrogate next to it is generated by the database.
One key, two kinds of member, and the INSERT has to treat them differently.

Nothing here touches a database: every assertion answers a question about what
the *model* would send, which is exactly the question the change is about.
"""

from __future__ import annotations

from typing import Annotated

import pytest

from rhosocial.activerecord.base.ddl import IdentityAttribute
from rhosocial.activerecord.base.fields import UseColumnAttributes
from rhosocial.activerecord.field.composite_pk import CompositePKMixin
from rhosocial.activerecord.model import ActiveRecord, AsyncActiveRecord

#: A database-generated key field. ``None`` default because the value does not
#: exist until the INSERT has run -- which is the whole point.
GeneratedId = Annotated[int | None, UseColumnAttributes(IdentityAttribute())]


class PartitionedLog(CompositePKMixin, ActiveRecord):
    """One key field the database generates, one the caller supplies."""

    __table_name__ = "ct_partitioned_log"
    __primary_key__ = ("id", "bucket")

    id: GeneratedId = None
    # A supplied key field is optional at declaration and required at save time:
    # nothing but the caller's own value can fill it.
    bucket: str | None = None
    job_id: int = 0


class AsyncPartitionedLog(CompositePKMixin, AsyncActiveRecord):
    """The asynchronous twin, so both _prepare_save_data paths are covered."""

    __table_name__ = "ct_partitioned_log"
    __primary_key__ = ("id", "bucket")

    id: GeneratedId = None
    bucket: str | None = None
    job_id: int = 0


class PlainComposite(CompositePKMixin, ActiveRecord):
    """A composite key with no generated member: every field is the caller's."""

    __table_name__ = "ct_plain_composite"
    __primary_key__ = ("order_id", "product_id")

    order_id: int = 0
    product_id: int = 0
    quantity: int = 0


class SingleKey(ActiveRecord):
    """The ordinary model this change must not disturb."""

    __table_name__ = "ct_single_key"

    id: int | None = None
    name: str = ""


@pytest.mark.parametrize("model", [PartitionedLog, AsyncPartitionedLog])
class TestDerivation:
    def test_which_key_fields_the_database_fills(self, model):
        assert model.identity_pk_fields() == ("id",)

    def test_which_key_fields_the_caller_must_give(self, model):
        assert model.required_pk_fields() == ("bucket",)

    def test_the_two_sets_partition_the_key(self, model):
        # No key field is both, and none is neither: the answer is total.
        assert set(model.identity_pk_fields()) | set(model.required_pk_fields()) == set(
            model.primary_key_fields()
        )
        assert not set(model.identity_pk_fields()) & set(model.required_pk_fields())

    def test_derivation_reads_the_column_declaration_not_a_second_flag(self, model):
        # The identity attribute is the same one the DDL renders
        # "GENERATED ... AS IDENTITY" from; there is no parallel declaration.
        assert [a.kind for a in model.column_attributes("id")] == ["identity"]
        assert model.column_attributes("bucket") == []


class TestInsertColumnList:
    def test_generated_key_field_is_left_out(self):
        row = PartitionedLog(bucket="202610", job_id=7)
        data = row._prepare_save_data()
        assert "id" not in data

    def test_caller_supplied_key_field_is_kept(self):
        # The regression that started this: the whole key used to be excluded,
        # so the partition column silently vanished from every INSERT.
        row = PartitionedLog(bucket="202610", job_id=7)
        data = row._prepare_save_data()
        assert data["bucket"] == "202610"
        assert data["job_id"] == 7

    def test_async_twin_keeps_the_caller_supplied_key_field(self):
        row = AsyncPartitionedLog(bucket="202610", job_id=7)
        data = row._prepare_save_data()
        assert "id" not in data
        assert data["bucket"] == "202610"

    def test_every_ordinary_column_still_travels(self):
        row = PartitionedLog(bucket="202610", job_id=7)
        data = row._prepare_save_data()
        assert set(data) == {"bucket", "job_id"}


class TestPlainCompositeIsUnchanged:
    def test_nothing_is_excluded_when_the_model_supplies_its_key(self):
        # __pk_auto_generated__ is False for a composite key because the
        # application writes every member; that decision is untouched.
        assert PlainComposite.identity_pk_fields() == ()
        row = PlainComposite(order_id=1, product_id=2, quantity=3)
        assert set(row._prepare_save_data()) == {"order_id", "product_id", "quantity"}

    def test_every_member_of_such_a_key_is_required(self):
        assert PlainComposite.required_pk_fields() == ("order_id", "product_id")


class TestSingleKeyIsUnchanged:
    def test_an_ordinary_key_is_still_excluded_whole(self):
        # A single-column surrogate key with no identity declaration keeps
        # exactly today's behaviour: excluded, and the database fills it.
        assert SingleKey.identity_pk_fields() == ()
        row = SingleKey(name="x")
        assert "id" not in row._prepare_save_data()
        assert row._prepare_save_data()["name"] == "x"

    def test_an_ordinary_key_requires_nothing_from_the_caller(self):
        assert SingleKey.required_pk_fields() == ()


class TestConstruction:
    def test_a_generated_key_field_may_be_left_unset(self):
        # Used to raise "Composite primary key field 'id' must be provided":
        # it cannot be provided, the value does not exist yet.
        row = PartitionedLog(bucket="202610")
        assert row.id is None

    def test_a_caller_supplied_key_field_may_not(self):
        with pytest.raises(ValueError, match="bucket"):
            PartitionedLog()
