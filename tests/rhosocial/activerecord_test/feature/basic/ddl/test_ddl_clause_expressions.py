def test_identity_clause_default_generation(dummy):
    sql, params = dummy.format_identity_clause(IdentityClause(dummy))
    assert sql == " GENERATED BY DEFAULT AS IDENTITY"
    assert params == ()


def test_identity_clause_always_and_attributes(dummy):
    clause = IdentityClause(dummy, "ALWAYS", start=10, increment=2, minvalue=1, maxvalue=100)
    sql, _ = dummy.format_identity_clause(clause)
    assert sql == (
        " GENERATED ALWAYS AS IDENTITY "
        "(START WITH 10 INCREMENT BY 2 MINVALUE 1 MAXVALUE 100)"
    )


def test_identity_clause_cycle_flags(dummy):
    assert dummy.format_identity_clause(IdentityClause(dummy, cycle=True))[0].endswith("(CYCLE)")
    assert dummy.format_identity_clause(IdentityClause(dummy, cycle=False))[0].endswith("(NO CYCLE)")


def _identity_column(dialect, **kwargs):
    from rhosocial.activerecord.base.ddl.attributes import IdentityAttribute

    col = _column(dialect)
    col.attributes = dialect.select_column_attributes([IdentityAttribute(**kwargs)])
    return col


def test_column_definition_identity_attribute(dummy):
    col = _identity_column(dummy, generation="BY DEFAULT", start=5)
    sql, _ = col.to_sql()
    assert sql == '"col" INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 5)'


def test_generic_column_definition_identity_attribute(sqlite):
    from rhosocial.activerecord.backend.dialect.mixins.ddl_column import DDLColumnMixin

    col = _identity_column(sqlite, generation="ALWAYS")
    sql, _ = DDLColumnMixin.format_column_definition(sqlite, col)
    assert sql == '"col" INTEGER GENERATED ALWAYS AS IDENTITY'


def test_generic_column_definition_identity_start_increment(sqlite):
    from rhosocial.activerecord.backend.dialect.mixins.ddl_column import DDLColumnMixin

    col = _identity_column(sqlite, generation="BY DEFAULT", start=2, increment=3)
    sql, _ = DDLColumnMixin.format_column_definition(sqlite, col)
    assert sql == '"col" INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 2 INCREMENT BY 3)'


def test_generic_column_definition_constraints_and_generated(sqlite):
    from rhosocial.activerecord.backend.dialect.mixins.ddl_column import DDLColumnMixin
    from rhosocial.activerecord.backend.expression.statements import (
        GeneratedColumnExpression,
        GeneratedColumnType,
    )

    constraint = ColumnConstraint(sqlite, ColumnConstraintType.NOT_NULL)
    generated = GeneratedColumnExpression(sqlite, IntegerType(sqlite), GeneratedColumnType.STORED)
    col = ColumnDefinition(
        sqlite, "col", IntegerType(sqlite), [constraint], generated_expression=generated
    )
    sql, _ = DDLColumnMixin.format_column_definition(sqlite, col)
    assert "NOT NULL" in sql


def test_generic_column_definition_renders_comment_when_supported(sqlite):
    from rhosocial.activerecord.backend.dialect.mixins.ddl_column import DDLColumnMixin

    class CommentDialect(SQLiteDialect):
        def supports_column_comment(self):
            return True

    dialect = CommentDialect((3, 53, 0))
    col = ColumnDefinition(dialect, "col", IntegerType(dialect), comment="hi")
    sql, _ = DDLColumnMixin.format_column_definition(dialect, col)
    assert sql.endswith("COMMENT 'hi'")


def test_generic_column_definition_comment_gate(sqlite):
    from rhosocial.activerecord.backend.dialect.mixins.ddl_column import DDLColumnMixin

    col = ColumnDefinition(sqlite, "col", IntegerType(sqlite), comment="hi")
    with pytest.raises(UnsupportedFeatureError, match="COMMENT"):
        DDLColumnMixin.format_column_definition(sqlite, col)


