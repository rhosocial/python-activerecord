# tests/rhosocial/activerecord_test/feature/basic/ddl/test_ddl_clause_expressions.py
"""Tests for the extracted DDL clause expressions.

Covers ``DefaultValueClause`` / ``IdentityClause`` / ``ReferencesClause`` and
their generic formatting, including the backend override seam (SQLite boolean
DEFAULT, identity attributes, referential actions / deferrability).
"""

import pytest

from rhosocial.activerecord.backend.dialect.exceptions import UnsupportedFeatureError
from rhosocial.activerecord.backend.expression import (
    ColumnConstraint,
    ColumnConstraintType,
    ColumnDefinition,
    DefaultValueClause,
    IdentityClause,
    ReferencesClause,
    TableConstraint,
    TableConstraintType,
)
from rhosocial.activerecord.backend.expression.statements import (
    ForeignKeyConstraint,
    ReferentialAction,
)
from rhosocial.activerecord.backend.expression.types import IntegerType
from rhosocial.activerecord.backend.impl.dummy import DummyDialect
from rhosocial.activerecord.backend.impl.sqlite.dialect import SQLiteDialect


@pytest.fixture
def dummy():
    return DummyDialect()


@pytest.fixture
def sqlite():
    return SQLiteDialect((3, 53, 0))


def _column(dialect, *constraints, **kwargs):
    return ColumnDefinition(dialect, "col", IntegerType(dialect), list(constraints), **kwargs)


# ---------------------------------------------------------------------------
# DefaultValueClause
# ---------------------------------------------------------------------------


def test_default_value_clause_scalar(dummy):
    clause = DefaultValueClause(dummy, 42)
    assert dummy.format_default_value_clause(clause) == ("42", ())


def test_default_value_clause_string_is_escaped(dummy):
    clause = DefaultValueClause(dummy, "o'brien")
    sql, params = dummy.format_default_value_clause(clause)
    assert sql == "'o''brien'"
    assert params == ()


def test_default_value_clause_expression(dummy):
    from rhosocial.activerecord.backend.expression import FunctionCall

    clause = DefaultValueClause(dummy, FunctionCall(dummy, "NOW"))
    sql, params = dummy.format_default_value_clause(clause)
    assert sql == "NOW()"
    assert params == ()


def test_default_value_clause_literal_is_inlined(dummy):
    from rhosocial.activerecord.backend.expression import Literal

    clause = DefaultValueClause(dummy, Literal(dummy, 7))
    sql, params = dummy.format_default_value_clause(clause)
    assert sql == "7"
    assert params == ()


def test_default_constraint_accepts_bare_value(dummy):
    constraint = ColumnConstraint(dummy, ColumnConstraintType.DEFAULT, default_value=5)
    sql, _ = dummy.format_default_constraint(constraint)
    assert sql == " DEFAULT 5"


def test_default_constraint_accepts_clause(dummy):
    clause = DefaultValueClause(dummy, "x")
    constraint = ColumnConstraint(dummy, ColumnConstraintType.DEFAULT, default_value=clause)
    sql, _ = dummy.format_default_constraint(constraint)
    assert sql == " DEFAULT 'x'"


def test_default_constraint_requires_value(dummy):
    constraint = ColumnConstraint(dummy, ColumnConstraintType.DEFAULT, default_value=None)
    with pytest.raises(ValueError, match="default value"):
        dummy.format_default_constraint(constraint)


def test_sqlite_boolean_default_is_inlined(sqlite):
    for value, expected in ((True, "1"), (False, "0")):
        clause = DefaultValueClause(sqlite, value)
        assert sqlite.format_default_value_clause(clause) == (expected, ())


def test_sqlite_string_default_still_escaped(sqlite):
    clause = DefaultValueClause(sqlite, "a'b")
    assert sqlite.format_default_value_clause(clause) == ("'a''b'", ())


