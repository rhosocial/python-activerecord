# tests/rhosocial/activerecord_test/feature/basic/connection/test_declaration_accessors.py
"""Declaration accessors: consumers read the accessor, not the dunder.

D3a: framework code that used to read a dunder directly now calls the
accessor, so a model that overrides the method is obeyed. Each rewritten
read site has a before/after test here -- the default behaviour is
unchanged (the accessor returns exactly what the dunder held), and an
override is now followed by the dependent answers.
"""
from rhosocial.activerecord.backend.impl.sqlite.backend import SQLiteBackend
from rhosocial.activerecord.backend.impl.sqlite.backend.async_backend import (
    AsyncSQLiteBackend,
)
from rhosocial.activerecord.backend.impl.sqlite.config import SQLiteConnectionConfig
from rhosocial.activerecord.model import AsyncActiveRecord, ActiveRecord

import pytest


class ApplicationKeyUser(ActiveRecord):
    @classmethod
    def table_name(cls):
        return "accessor_application_key_users"

    @classmethod
    def primary_key(cls):
        return ("code", "bucket")

    @classmethod
    def pk_auto_generated(cls):
        return False

    code: str
    bucket: str


class SurrogateKeyUser(ActiveRecord):
    @classmethod
    def table_name(cls):
        return "accessor_surrogate_key_users"

    id: int
    code: str


class OverriddenAutoKeyUser(SurrogateKeyUser):
    """Same dunder as its parent, but the method answers differently."""

    @classmethod
    def pk_auto_generated(cls) -> bool:
        return False


class TestPkAutoGeneratedAccessor:
    def test_declared_flag_is_returned(self):
        assert SurrogateKeyUser.pk_auto_generated() is True
        assert ApplicationKeyUser.pk_auto_generated() is False

    def test_override_changes_the_dependent_answers(self):
        # The point of the accessor: every key question that used to read
        # the dunder now reads the method, so an override is obeyed across
        # the board instead of being bypassed by some readers.
        assert OverriddenAutoKeyUser.pk_auto_generated() is False
        assert OverriddenAutoKeyUser.required_pk_fields() == ("id",)
        assert OverriddenAutoKeyUser._insert_pk_exclusions() == set()
        # ...and the un-overridden parent still answers from its declaration.
        assert SurrogateKeyUser.pk_auto_generated() is True
        assert SurrogateKeyUser.required_pk_fields() == ()

    def test_override_is_inherited_by_subclasses(self):
        class SubclassOf(OverriddenAutoKeyUser):
            @classmethod
            def table_name(cls):
                return "accessor_subclass_of_overridden"

        assert SubclassOf.pk_auto_generated() is False


class TestConnectionAccessors:
    def test_before_configuration_they_are_none(self):
        class Unconfigured(ActiveRecord):
            @classmethod
            def table_name(cls):
                return "accessors_unconfigured"

            id: int

        assert Unconfigured.backend_class() is None
        assert Unconfigured.connection_config() is None
        # Logging is the exception: the framework installs a default config
        # at import, so the accessor reports that default, not None.
        assert Unconfigured.logging_config() is not None

    def test_configure_writes_what_the_accessors_read(self, tmp_path):
        config = SQLiteConnectionConfig(database=str(tmp_path / "accessors.db"))

        class Configured(ActiveRecord):
            @classmethod
            def table_name(cls):
                return "accessors_configured"

            id: int

        Configured.configure(config, SQLiteBackend)
        assert Configured.backend_class() is SQLiteBackend
        assert Configured.connection_config() is config

    @pytest.mark.asyncio
    async def test_async_configure_writes_what_the_accessors_read(self, tmp_path):
        config = SQLiteConnectionConfig(database=str(tmp_path / "accessors_async.db"))

        class AsyncConfigured(AsyncActiveRecord):
            @classmethod
            def table_name(cls):
                return "accessors_configured_async"

            id: int

        await AsyncConfigured.configure(config, AsyncSQLiteBackend)
        assert AsyncConfigured.backend_class() is AsyncSQLiteBackend
        assert AsyncConfigured.connection_config() is config


class TestFeatureLocatorAccessors:
    """The P0 appendix items: logger name and no-track fields as accessors."""

    def test_logger_name_defaults_to_none_then_is_overridable(self):
        class Named(ActiveRecord):
            @classmethod
            def table_name(cls):
                return "accessors_named"

            __logger_name__ = "myapp.named"

            id: int

        class Unnamed(ActiveRecord):
            @classmethod
            def table_name(cls):
                return "accessors_unnamed"

            id: int

        assert Named.logger_name() == "myapp.named"
        assert Unnamed.logger_name() is None
        # The consumer obeys the override instead of reading the flag.
        assert Named._get_logger_name() == "myapp.named"

    def test_no_track_fields_is_the_mro_union(self):
        class TrackingMixin(ActiveRecord):
            __no_track_fields__ = {"from_mixin"}

            id: int

        class Joined(TrackingMixin):
            @classmethod
            def table_name(cls):
                return "accessors_joined"

            __no_track_fields__ = {"from_model"}

        class Inheritor(Joined):
            @classmethod
            def table_name(cls):
                return "accessors_inheritor"

        assert Joined.no_track_fields() == {"from_mixin", "from_model"}
        # A subclass that declares nothing still inherits the mixin's share:
        # the union climbs, so a mixin added higher in the MRO lands here.
        assert "from_mixin" in Inheritor.no_track_fields()
        # The snapshot attribute is gone: the accessor is the only reader,
        # so a flat copy cannot go stale against a late mixin.
        assert "no_track_fields" not in Joined.__dict__
