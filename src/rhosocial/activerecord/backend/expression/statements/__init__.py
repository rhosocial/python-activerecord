import importlib

_MODULES = ('_types', 'ddl_alter', 'ddl_comment', 'ddl_database', 'ddl_domain', 'ddl_function', 'ddl_index', 'ddl_partition', 'ddl_schema', 'ddl_sequence', 'ddl_table', 'ddl_trigger', 'ddl_truncate', 'ddl_type', 'ddl_view', 'dml', 'dql', 'executable', 'execution_testing', 'explain', 'filter_clause', 'fulltext_match', 'graph', 'transaction')


def __getattr__(name):
    """Resolve a public name from this namespace lazily (no import cycles)."""
    for module_name in _MODULES:
        module = importlib.import_module(f'.{module_name}', __name__)
        if name in vars(module):
            value = vars(module)[name]
            globals()[name] = value  # cache so vars()/inspect see the name
            return value
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
