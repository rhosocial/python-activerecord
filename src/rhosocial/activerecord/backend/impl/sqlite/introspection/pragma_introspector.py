# src/rhosocial/activerecord/backend/impl/sqlite/introspection/pragma_introspector.py
"""
SQLite PRAGMA sub-introspectors.

Provides direct access to SQLite's PRAGMA interface. These classes do not
inherit from AbstractIntrospector — they are purpose-built "sub-introspectors"
exposed as the `.pragma` property on SQLiteIntrospector and
AsyncSQLiteIntrospector.

Design principle: Sync and Async are separate and cannot coexist.
- PragmaIntrospector: for synchronous backends (method names without _async suffix)
- AsyncPragmaIntrospector: for asynchronous backends (method names without _async suffix)

Usage::

    # Synchronous
    mode = backend.introspector.pragma.get("journal_mode")
    backend.introspector.pragma.set("journal_mode", "WAL")
    cols = backend.introspector.pragma.table_info("users")
    errors = backend.introspector.pragma.integrity_check()

    # Asynchronous
    mode = await backend.introspector.pragma.get("journal_mode")
    backend.introspector.pragma.set("journal_mode", "WAL")
    cols = await backend.introspector.pragma.table_info("users")
"""

from typing import Any, Dict, List, Optional

from rhosocial.activerecord.backend.introspection.executor import (
    IntrospectorExecutor,
    AsyncIntrospectorExecutor,
)


#: The WAL checkpoint mode used when the caller names none.
#:
#: ``PASSIVE`` is the only mode that never blocks: it checkpoints as much as
#: it can without waiting for readers or writers, so a caller who has not
#: thought about checkpointing gets the one mode that cannot stall. ``FULL``
#: waits for readers, ``RESTART`` and ``TRUNCATE`` wait for writers too.
#: Both the sync and the async introspector run the same PRAGMA, so they
#: answer one question with one mode; per ``.claude/rules/constants.md`` a
#: value read from more than one function, where the readings must agree,
#: takes a module-level constant and a test that pins it -- see
#: ``tests/rhosocial/activerecord_test/feature/rules/test_shared_defaults.py``.
WAL_CHECKPOINT_DEFAULT_MODE: str = "PASSIVE"


class PragmaIntrospector:
    """Synchronous PRAGMA introspector for SQLite backends.

    All methods are synchronous. Method names do NOT have an _async suffix.
    """

    def __init__(self, backend: Any, executor: IntrospectorExecutor) -> None:
        self._backend = backend
        self._executor = executor

    # ------------------------------------------------------------------ #
    # Core PRAGMA operations
    # ------------------------------------------------------------------ #

    def get(
        self,
        name: str,
        argument: Optional[Any] = None,
        schema: Optional[str] = None,
    ) -> Optional[Any]:
        """Read a PRAGMA value.

        Returns the first row returned by the PRAGMA, or ``None`` if the
        result is empty (e.g. write-only or action PRAGMAs).
        """
        sql, params = self._backend.dialect.pragma_query_statement(name, argument, schema).to_sql()
        rows = self._executor.execute(sql, params)
        return rows[0] if rows else None

    def set(
        self,
        name: str,
        value: Any,
        schema: Optional[str] = None,
    ) -> None:
        """Write a PRAGMA value (for read/write PRAGMAs)."""
        sql, params = self._backend.dialect.pragma_set_statement(name, value, schema=schema).to_sql()
        self._executor.execute(sql, params)

    def execute(
        self,
        name: str,
        argument: Optional[Any] = None,
        schema: Optional[str] = None,
    ) -> List[Dict[str, Any]]:
        """Execute any PRAGMA and return all result rows as dicts.

        Use this for PRAGMAs that return multiple rows (e.g.
        ``table_info``, ``index_list``, ``foreign_key_list``).
        """
        sql, params = self._backend.dialect.pragma_query_statement(name, argument, schema).to_sql()
        return self._executor.execute(sql, params)

    # ------------------------------------------------------------------ #
    # Commonly used structural PRAGMAs
    # ------------------------------------------------------------------ #

    def table_info(self, table_name: str, schema: Optional[str] = None) -> List[Dict[str, Any]]:
        """Return raw ``PRAGMA table_info(table_name)`` rows."""
        return self.execute("table_info", self._backend.dialect.format_identifier(table_name), schema)

    def table_xinfo(self, table_name: str, schema: Optional[str] = None) -> List[Dict[str, Any]]:
        """Return raw ``PRAGMA table_xinfo(table_name)`` rows (SQLite 3.26+).

        Includes hidden columns generated by virtual tables.
        """
        return self.execute("table_xinfo", self._backend.dialect.format_identifier(table_name), schema)

    def index_list(self, table_name: str, schema: Optional[str] = None) -> List[Dict[str, Any]]:
        """Return raw ``PRAGMA index_list(table_name)`` rows."""
        return self.execute("index_list", self._backend.dialect.format_identifier(table_name), schema)

    def index_info(self, index_name: str, schema: Optional[str] = None) -> List[Dict[str, Any]]:
        """Return raw ``PRAGMA index_info(index_name)`` rows."""
        return self.execute("index_info", self._backend.dialect.format_identifier(index_name), schema)

    def index_xinfo(self, index_name: str, schema: Optional[str] = None) -> List[Dict[str, Any]]:
        """Return raw ``PRAGMA index_xinfo(index_name)`` rows (SQLite 3.9+)."""
        return self.execute("index_xinfo", self._backend.dialect.format_identifier(index_name), schema)

    def foreign_key_list(self, table_name: str, schema: Optional[str] = None) -> List[Dict[str, Any]]:
        """Return raw ``PRAGMA foreign_key_list(table_name)`` rows."""
        return self.execute("foreign_key_list", self._backend.dialect.format_identifier(table_name), schema)

    def table_list(self, schema: Optional[str] = None) -> List[Dict[str, Any]]:
        """Return raw ``PRAGMA table_list`` rows (SQLite 3.37+)."""
        return self.execute("table_list", schema=schema)

    # ------------------------------------------------------------------ #
    # Configuration / maintenance PRAGMAs
    # ------------------------------------------------------------------ #

    def integrity_check(self, schema: Optional[str] = None) -> List[str]:
        """Run ``PRAGMA integrity_check`` and return error message strings.

        Returns ``["ok"]`` if the database is intact.
        """
        rows = self.execute("integrity_check", schema=schema)
        return [list(row.values())[0] for row in rows if row]

    def foreign_key_check(
        self,
        table_name: Optional[str] = None,
        schema: Optional[str] = None,
    ) -> List[Dict[str, Any]]:
        """Run ``PRAGMA foreign_key_check`` (optionally for a single table).

        Returns rows describing foreign-key constraint violations.
        """
        arg = self._backend.dialect.format_identifier(table_name) if table_name else None
        return self.execute("foreign_key_check", arg, schema)

    def journal_mode(self, schema: Optional[str] = None) -> Optional[str]:
        """Return the current journal mode."""
        row = self.get("journal_mode", schema=schema)
        if row is None:
            return None
        return list(row.values())[0] if row else None

    def wal_checkpoint(
        self,
        mode: str = WAL_CHECKPOINT_DEFAULT_MODE,
        schema: Optional[str] = None,
    ) -> Optional[Dict[str, Any]]:
        """Run a WAL checkpoint.

        Args:
            mode:   One of ``PASSIVE``, ``FULL``, ``RESTART``, ``TRUNCATE``.
                Defaults to :data:`WAL_CHECKPOINT_DEFAULT_MODE`.
            schema: Attached-database name, or ``None`` for the main DB.
        """
        return self.get("wal_checkpoint", mode, schema)


